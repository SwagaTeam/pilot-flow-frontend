// Types and read-only examples are derived from the authoritative checked-in contract.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const spec = JSON.parse(readFileSync(new URL('../openapi.json', import.meta.url), 'utf8'));
function type(schema) {
  let result;
  if (schema.$ref) result = schema.$ref.split('/').at(-1);
  else if (schema.enum)
    result = [...new Set(schema.enum.map((v) => JSON.stringify(v)))].join(' | ');
  else if (schema.type === 'array') result = `Array<${type(schema.items)}>`;
  else if (schema.type === 'object')
    result = `{\n${Object.entries(schema.properties ?? {})
      .map(
        ([key, value]) => `  ${key}${schema.required?.includes(key) ? '' : '?'}: ${type(value)};`,
      )
      .join('\n')}\n}`;
  else
    result =
      { string: 'string', integer: 'number', number: 'number', boolean: 'boolean' }[schema.type] ??
      'unknown';
  return schema.nullable && !result.split(' | ').includes('null') ? `${result} | null` : result;
}
mkdirSync(new URL('../src/app/core', import.meta.url), { recursive: true });
mkdirSync(new URL('../public', import.meta.url), { recursive: true });
writeFileSync(
  new URL('../src/app/core/models.ts', import.meta.url),
  '// Generated by npm run generate:contract. Do not edit. Decimal values remain strings.\n\n' +
    Object.entries(spec.components.schemas)
      .map(([name, schema]) => `export type ${name} = ${type(schema)};`)
      .join('\n\n') +
    '\n',
);
const examples = Object.fromEntries(
  Object.entries(spec.paths)
    .filter(
      ([, methods]) =>
        methods.get?.responses?.['200']?.content?.['application/json']?.example !== undefined,
    )
    .map(([path, methods]) => [
      path,
      methods.get.responses['200'].content['application/json'].example,
    ]),
);
writeFileSync(new URL('../public/demo-responses.json', import.meta.url), JSON.stringify(examples));
console.log(
  `Generated ${Object.keys(spec.components.schemas).length} DTO types and ${Object.keys(examples).length} read-only responses.`,
);
